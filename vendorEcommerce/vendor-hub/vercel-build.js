/**
 * vercel-build.js
 *
 * Universal pre-deployment build script for Vercel & local environments.
 * Supports running from repository root, subdirectories (vendor-hub, vendorEcommerce),
 * or directly inside vendor-hub/index.html.
 */

const fs   = require('fs');
const path = require('path');

// Locate the directory that contains the real index.html file
function findSourceDir() {
  const cwd = process.cwd();
  const dir = __dirname;

  const candidates = [
    // 1. Check if current directory has index.html as a file
    cwd,
    // 2. Check vendor-hub/index.html directory
    path.join(cwd, 'vendor-hub', 'index.html'),
    path.join(dir, 'vendor-hub', 'index.html'),
    // 3. Check vendorEcommerce/vendor-hub directory
    path.join(cwd, 'vendorEcommerce', 'vendor-hub'),
    path.join(dir, 'vendorEcommerce', 'vendor-hub'),
    // 4. Check index.html subfolder from current position
    path.join(cwd, 'index.html'),
    path.join(dir, 'index.html'),
    // 5. Parent fallbacks
    path.join(cwd, '..', 'vendorEcommerce', 'vendor-hub'),
    path.join(dir, '..', 'vendorEcommerce', 'vendor-hub')
  ];

  for (const candidate of candidates) {
    try {
      const testFile = path.join(candidate, 'index.html');
      if (fs.existsSync(testFile) && fs.statSync(testFile).isFile()) {
        return candidate;
      }
    } catch (_) {}
  }

  // Fallback: search for any index.html file
  return dir;
}

const SOURCE_DIR = findSourceDir();
const DIST_DIR   = path.join(process.cwd(), 'dist');

console.log(`[Vercel Build] Working Directory: ${process.cwd()}`);
console.log(`[Vercel Build] Resolved Source:   ${SOURCE_DIR}`);
console.log(`[Vercel Build] Target Output:     ${DIST_DIR}`);

// Files and directories to exclude when staging web distribution
const EXCLUDED_ENTRIES = new Set([
  'node_modules',
  '.git',
  '.github',
  'dist',
  'vendor-hub',
  'vendorEcommerce',
  'test-project.js',
  'firestore.rules',
  'firebase.json',
  '.env.example',
  '.env.local.example',
  '.gitignore',
  'DEPLOYMENT.md',
  'README.md',
  'SECURITY.md',
  'package.json',
  'package-lock.json',
  'vercel-build.js',
  'vercel.json',
  'LICENSE'
]);

function copyDir(src, dest) {
  if (!fs.existsSync(dest)) fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (EXCLUDED_ENTRIES.has(entry.name)) continue;
    const srcPath  = path.join(src,  entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      // Don't recurse into index.html directory if copying from vendor-hub
      if (entry.name === 'index.html' && path.relative(srcPath, destPath) === '') continue;
      copyDir(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

if (path.resolve(SOURCE_DIR) !== path.resolve(DIST_DIR)) {
  if (fs.existsSync(DIST_DIR)) {
    try { fs.rmSync(DIST_DIR, { recursive: true, force: true }); } catch (_) {}
  }
  fs.mkdirSync(DIST_DIR, { recursive: true });
  copyDir(SOURCE_DIR, DIST_DIR);
  console.log('    ✓ Static site assets staged to dist/');
}

// Generate __env.js from environment variables
const envConfig = {
  VITE_FIREBASE_API_KEY:             process.env.VITE_FIREBASE_API_KEY             || '',
  VITE_FIREBASE_AUTH_DOMAIN:         process.env.VITE_FIREBASE_AUTH_DOMAIN         || '',
  VITE_FIREBASE_PROJECT_ID:          process.env.VITE_FIREBASE_PROJECT_ID          || '',
  VITE_FIREBASE_STORAGE_BUCKET:      process.env.VITE_FIREBASE_STORAGE_BUCKET      || '',
  VITE_FIREBASE_MESSAGING_SENDER_ID: process.env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
  VITE_FIREBASE_APP_ID:              process.env.VITE_FIREBASE_APP_ID              || '',
  VITE_FIREBASE_MEASUREMENT_ID:      process.env.VITE_FIREBASE_MEASUREMENT_ID      || '',
  VITE_GEMINI_API_KEY:               process.env.VITE_GEMINI_API_KEY               || '',
};

const envContent = `// Auto-generated by vercel-build.js — DO NOT EDIT OR COMMIT THIS FILE\nwindow.__env = ${JSON.stringify(envConfig, null, 2)};\n`;

// Write to dist assets
const distEnvDir = path.join(DIST_DIR, 'assets', 'js', 'config');
if (!fs.existsSync(distEnvDir)) fs.mkdirSync(distEnvDir, { recursive: true });
fs.writeFileSync(path.join(distEnvDir, '__env.js'), envContent);

// Also write in-place to source if it has assets/js/config
const srcEnvDir = path.join(SOURCE_DIR, 'assets', 'js', 'config');
if (fs.existsSync(srcEnvDir)) {
  fs.writeFileSync(path.join(srcEnvDir, '__env.js'), envContent);
}

// Ensure .nojekyll exists in dist for GitHub Pages compatibility
const distNoJekyll = path.join(DIST_DIR, '.nojekyll');
if (!fs.existsSync(distNoJekyll)) {
  fs.writeFileSync(distNoJekyll, '');
}

console.log('    ✓ __env.js runtime environment injected');
console.log('    ✓ .nojekyll static compatibility confirmed');
console.log('\n✅  Build complete — ready for Vercel deployment.\n');
